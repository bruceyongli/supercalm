import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, lstat, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes } from 'node:crypto';
const dir = await mkdtemp(join(tmpdir(), 'aios-test-pairing-'));
process.env.AIOS_DATA = dir;
process.env.AIOS_EXECUTION_NODES_FILE = join(dir, 'registry.json');
process.env.AIOS_ENV_FILE = join(dir,'absent.env');
try {
  const {checkPairingTarget, preparePairing, claimPairing} = await import('../src/execution_pairing.js');
  const {saveExecutionNode, loadExecutionNodes} = await import('../src/execution_transport.js');
  const {reserveWorker} = await import('../bin/execution-pair-target.mjs');
  const homeDir = join(dir,'remote-home'); await mkdir(homeDir);
  const platform = {homeDir, check:()=>{}, loaded:()=>false, ports:()=>{}};
  const credential = randomBytes(32).toString('hex');
  await assert.rejects(reserveWorker(credential,{...platform,loaded:()=>true}),/already a controller/);
  await assert.rejects(reserveWorker(credential,{...platform,loaded:label=>label.endsWith('executor')}),/already has a worker/);
  const ready = await reserveWorker(credential,platform); assert.deepEqual(await reserveWorker(credential,platform),ready);
  await assert.rejects(reserveWorker(randomBytes(32).toString('hex'),platform),/another worker/);
  assert.equal((await readFile(join(ready.root,'control-token'),'utf8')).trim(),credential);
  const old = { id:'default-mac',host:'existing.invalid',label:'Original',root:'/fixture/root',
    token:randomBytes(32).toString('hex'),localPort:18893,remotePort:8794,callbackPort:18793,default:true };
  await saveExecutionNode(old);
  const original = (await loadExecutionNodes())[0];
  const target = {id:'new-mac',host:'user@new.invalid',commit:'9'.repeat(40)};
  for (const host of ['-F bad','a;ls','user@localhost','127.0.0.2','user@box\nother','user@user@box']) assert.throws(() => checkPairingTarget(target.id,host));
  for (const id of ['local','../box','Big','--id','3box']) assert.throws(() => checkPairingTarget(id,target.host));
  let installs = 0, token;
  const install = async p => { installs++; if (token) assert.equal(p.token,token); else token=p.token; return '/fixture/new-mac'; };
  await assert.rejects(preparePairing({...target,host:'me@EXISTING.INVALID'},install), /already registered/);
  assert.equal(installs,0);
  await assert.rejects(preparePairing(target,async p => {token=p.token; throw Error('Interrupted before verification');}), /Interrupted/);
  const file = join(dir,'execution-pairings',target.id+'.json');
  assert.equal(JSON.parse(await readFile(file,'utf8')).hash,undefined);
  await assert.rejects(preparePairing({...target,host:'another.invalid'},install), /another SSH host/);
  const c1 = await preparePairing(target,install), c2 = await preparePairing(target,install);
  assert.notEqual(c1,c2);
  await assert.rejects(claimPairing(c1,target.commit), /invalid, expired/);
  const record = await readFile(file,'utf8');
  assert.ok(!record.includes(c2)); assert.equal((await lstat(file)).mode & 0o777,0o600);
  await writeFile(file,JSON.stringify({...JSON.parse(record),expires:1}));
  await assert.rejects(claimPairing(c2,target.commit), /invalid, expired/);
  await writeFile(file,record);
  await assert.rejects(claimPairing(c2,'8'.repeat(40)), /updated/);
  assert.deepEqual(await loadExecutionNodes(),[original]);
  const pair = await Promise.allSettled([claimPairing(c2,target.commit),claimPairing(c2,target.commit)]);
  const ok = pair.filter(r=>r.status==='fulfilled');
  assert.equal(ok.length,1); assert.deepEqual(ok[0].value,{id:'new-mac',label:'new-mac'});
  const nodes = await loadExecutionNodes();
  assert.equal(nodes.length,2); assert.deepEqual(nodes[0],original); assert.equal(nodes[1].default,false);
  assert.notEqual(nodes[1].localPort,old.localPort); assert.equal(nodes[1].token, token);
  await assert.rejects(claimPairing(c2,target.commit),/invalid, expired/);
  await assert.rejects(preparePairing(target,install),/already registered/);
  assert.equal(installs,2);
  const {exercisePairingCLI}=await import('./fixtures/execution-pair-cli.mjs');await exercisePairingCLI(dir);
  console.log('PASS: exact target, existing default preserved, retry/expiry/release binding and atomic single-use registration');
} finally {await rm(dir,{recursive:true,force:true});}
