import assert from 'node:assert/strict';
import { mkdtemp, realpath, mkdir, writeFile, readFile, cp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
const exec = promisify(execFile), root = await realpath(await mkdtemp(join(tmpdir(), 'aios-execution-archive-')));
process.env.AIOS_DATA = join(root, 'data');
process.env.AIOS_WORKTREE_ROOT = join(root, 'worktrees');
process.env.AIOS_LIVE_STORAGE_CONFIG = join(root, 'no-storage.json');
try {
  const repo = join(root, 'repo'), tree = join(root, 'worktrees/project/s_old'), archive = join(root, 'remote/archive/s_old');
  await mkdir(repo); await mkdir(join(root, 'worktrees/project'), { recursive: true });
  const git = async (...args) => (await exec('/usr/bin/git', ['-C', repo, ...args])).stdout.trim();
  await git('init', '-b', 'main'); await git('config', 'user.email', 'test@example.invalid'); await git('config', 'user.name', 'Fixture');
  await writeFile(join(repo, 'plan.md'), 'base'); await git('add', '.'); await git('commit', '-m', 'base');
  await git('worktree', 'add', '-b', 'original-session', tree);
  await writeFile(join(tree, 'plan.md'), 'staged'); await exec('/usr/bin/git', ['-C', tree, 'add', '.']);
  await writeFile(join(tree, 'plan.md'), 'dirty'); await writeFile(join(tree, 'extra.md'), 'untracked');
  await cp(tree, archive, { recursive: true }); await rm(tree, { recursive: true });
  const { archivedGitEvidence, archivedWorkingArchive } = await import('../src/execution_archive.js');
  const { archiveWorker } = await import('../src/archive_transport.js');
  const totals = await archiveWorker({ root: archive, op: 'digest', contents: false });
  const record = { ...totals, fingerprint: 'old-local-inodes-not-remote-inodes', sourceRoot: tree, host: 'fixture', remoteRoot: archive, kind: 'worktree' };
  const request = async (_host, query) => query.op === 'read' ? readFile(join(query.root, query.path)) : archiveWorker(query);
  const evidence = await archivedGitEvidence(record, repo, { request });
  assert.equal(evidence.head, await git('rev-parse', 'original-session'));
  assert.equal(evidence.branch, 'original-session'); assert.equal(evidence.statusHash, null);
  assert.equal(evidence.archiveFingerprint, totals.fingerprint, 'bind remote stability, not old local inode fingerprint');
  assert.ok(evidence.indexReceipt.sha256);
  const descriptor = archivedWorkingArchive(record);
  assert.equal(descriptor.command, '/usr/bin/ssh'); assert.match(descriptor.args.at(-1), /--exclude=\.\/\.git/);
  assert.doesNotMatch(archivedWorkingArchive({ ...record, kind: undefined }).args.at(-1), /--exclude/, 'artifact repositories are preserved');
  await assert.rejects(archivedGitEvidence({ ...record, files: totals.files + 1 }, repo, { request }), /inventory changed/);
  await assert.rejects(archivedGitEvidence({ ...record, sourceRoot: join(root, 'another-session') }, repo, { request }), /identity differs/);
  const brokenRequest = async (_host, query) => query.op === 'read' ? Buffer.from('gitdir: ' + join(repo, '.git') + '\n') : request(_host, query);
  await assert.rejects(archivedGitEvidence(record, repo, { request: brokenRequest }), /another repository/);
  assert.equal(await readFile(join(archive, 'plan.md'), 'utf8'), 'dirty');
  console.log('execution_archive: missing checkout, exact Git registration/index, remote fingerprint and originals passed');
} finally { await rm(root, { recursive: true, force: true }); }
