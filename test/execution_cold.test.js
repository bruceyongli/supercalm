import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, symlink, lstat, rm, realpath } from 'node:fs/promises';
import { createWriteStream } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn, execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { pipeline } from 'node:stream/promises';

const root = await realpath(await mkdtemp(join(tmpdir(), 'aios-cold-test-'))), exec = promisify(execFile);
process.env.AIOS_DATA = join(root, 'data'); process.env.AIOS_WORKTREE_ROOT = join(root, 'worktrees');
try {
  const source = join(root, 'source'), target = join(root, 'target'), sid = 's_cold_fixture';
  await mkdir(source); await mkdir(target);
  const git = async (...args) => (await exec('/usr/bin/git', ['-C', source, ...args])).stdout;
  await git('init', '-b', 'main'); await git('config', 'user.email', 'test@localhost'); await git('config', 'user.name', 'Fixture');
  await writeFile(join(source, '.gitignore'), 'node_modules/\ndist/\nreports/\n*.tsbuildinfo\n');
  await writeFile(join(source, 'source.txt'), 'original');
  await mkdir(join(source, 'dist')); await writeFile(join(source, 'dist', 'source.txt'), 'tracked in a build-named directory');
  await git('add', '.'); await git('add', '-f', 'dist/source.txt'); await git('commit', '-m', 'source');
  await writeFile(join(source, 'source.txt'), 'staged'); await git('add', 'source.txt');
  await writeFile(join(source, 'source.txt'), 'unstaged'); await writeFile(join(source, 'new-source.txt'), 'untracked source');
  await mkdir(join(source, 'desktop/electron-dist'), { recursive: true });
  await writeFile(join(source, 'desktop/electron-dist/runtime.bin'), 'old rebuildable runtime');
  await mkdir(join(source, 'app/dist'), { recursive: true }); await writeFile(join(source, 'app/dist/cache.bin'), 'ignored build');
  await mkdir(join(source, 'reports')); await writeFile(join(source, 'reports/plan.md'), '# Important report');
  await writeFile(join(source, 'build.tsbuildinfo'), 'generated cache');
  const modules = join(process.env.AIOS_DATA, 'session-storage', sid, 'node_modules');
  await mkdir(modules, { recursive: true }); await writeFile(join(modules, 'old.js'), 'obsolete dependency');
  await symlink(modules, join(source, 'node_modules'));
  const { planColdWorkingFiles, validateColdBuildPaths } = await import('../src/execution_cold.js');
  const { portableWorkingArchive, portableArtifactArchive } = await import('../src/execution_tree.js');
  const { gitEvidence, validateArchive } = await import('../src/execution_bundle.js');
  for (const path of ['../dist', '/dist', 'reports', 'x/../../dist', 'x\\dist']) assert.throws(() => validateColdBuildPaths([path]));
  await assert.rejects(planColdWorkingFiles(source, { coldBuildPaths: ['dist'] }), /tracked source/);
  const before = await gitEvidence(source);
  const plan = await planColdWorkingFiles(source, { coldBuildPaths: ['desktop/electron-dist'] });
  assert.deepEqual(plan.entries.map(e => e.path).sort(), ['app/dist', 'build.tsbuildinfo', 'desktop/electron-dist']);
  const kept = await gitEvidence(source, { excludedPaths: plan.entries.map(e => e.path) });
  const archive = await portableWorkingArchive(source, sid, plan);
  assert.equal(archive.links[0].rebuild, true);
  const file = join(root, 'tree.tar'), child = spawn(archive.command, archive.args, { stdio: ['ignore', 'pipe', 'inherit'] });
  await Promise.all([pipeline(child.stdout, createWriteStream(file)), new Promise((r,j) => { child.on('error',j); child.on('close',c => c === 0 ? r() : j(Error('export failed'))); })]);
  await validateArchive(file);
  await exec('/usr/bin/tar', ['-xf', file, '-C', target]);
  for (const path of ['desktop/electron-dist', 'app/dist', 'build.tsbuildinfo', 'node_modules/old.js']) await assert.rejects(lstat(join(target, path)), { code: 'ENOENT' });
  assert.equal((await lstat(join(target, 'node_modules'))).isSymbolicLink(), true);
  assert.equal((await lstat(join(target, '.aios/execution-dependencies/0'))).isDirectory(), true);
  assert.equal(await readFile(join(target, 'reports/plan.md'), 'utf8'), '# Important report');
  assert.equal(await readFile(join(target, 'dist/source.txt'), 'utf8'), 'tracked in a build-named directory');
  assert.equal(await readFile(join(target, 'new-source.txt'), 'utf8'), 'untracked source');
  // Restore real Git/index, then prove only the explicit cold files differ.
  await exec('/usr/bin/git', ['clone', '--bare', source, join(target, '.git')]);
  await exec('/usr/bin/git', ['--git-dir=' + join(target, '.git'), 'config', 'core.bare', 'false']);
  const { copyFile } = await import('node:fs/promises');
  await copyFile(join(source, '.git/index'), join(target, '.git/index'));
  await writeFile(join(target, '.git/info/exclude'), '/.aios/execution-dependencies/\n');
  assert.equal((await gitEvidence(target)).statusHash, kept.statusHash);
  assert.equal((await gitEvidence(source)).statusHash, before.statusHash);
  assert.equal(await readFile(join(source, 'desktop/electron-dist/runtime.bin'), 'utf8'), 'old rebuildable runtime');
  assert.equal(await readFile(join(modules, 'old.js'), 'utf8'), 'obsolete dependency');
  const artifacts = join(root, 'artifacts'); await mkdir(join(artifacts, 'runtime/venv'), {recursive:true});
  await mkdir(join(artifacts, 'notes/venv'), {recursive:true});
  await mkdir(join(artifacts, 'node_modules')); await writeFile(join(artifacts, 'node_modules/dep.js'), 'old dependency');
  await writeFile(join(artifacts, 'runtime/venv/pyvenv.cfg'), 'home = python');
  await writeFile(join(artifacts, 'notes/venv/plan.md'), 'not a Python environment');
  await writeFile(join(artifacts, 'report.html'), '<h1>Keep the report</h1>');
  await mkdir(join(artifacts,'Desktop.app/Contents'),{recursive:true});
  await writeFile(join(artifacts,'Desktop.app/Contents/Info.plist'),'<plist/>');
  await writeFile(join(artifacts,'Desktop.dmg'),'built disk image');
  await exec('/usr/bin/zip',['-q','Desktop.zip','Desktop.app/Contents/Info.plist'],{cwd:artifacts});
  await exec('/usr/bin/zip',['-q','source.zip','report.html'],{cwd:artifacts});
  const artifactArchive = portableArtifactArchive(artifacts, {rebuildDependencies:true});
  const a = spawn(artifactArchive.command, artifactArchive.args, {stdio:['ignore','pipe','inherit']}), af = join(root,'artifacts.tar');
  await Promise.all([pipeline(a.stdout, createWriteStream(af)),new Promise((r,j)=>{a.on('error',j);a.on('close',c=>c===0?r():j(Error('artifact export failed')));})]);
  const names = (await exec('/usr/bin/tar',['-tf',af])).stdout;
  assert.ok(names.includes('./report.html')); assert.ok(names.includes('./notes/venv/plan.md'));
  assert.ok(!names.includes('./node_modules')); assert.ok(!names.includes('./runtime/venv'));
  for (const path of ['Desktop.app','Desktop.dmg','Desktop.zip']) assert.ok(!names.includes('./'+path));
  assert.ok(names.includes('./source.zip'),'source archives are not treated as compiled applications');
  assert.equal(await readFile(join(artifacts,'Desktop.app/Contents/Info.plist'),'utf8'),'<plist/>');
  assert.equal(await readFile(join(artifacts,'runtime/venv/pyvenv.cfg'),'utf8'),'home = python');
  for (const path of ['screenshot.png','recording.mp4','debug.json','trace.jsonl','trace.log']) await writeFile(join(artifacts,path),'cold historical data');
  await mkdir(join(artifacts,'debug')); await writeFile(join(artifacts,'debug/report.md'),'# Report in a debug directory');
  await writeFile(join(artifacts,'results.csv'),'word,result\n你好,ok\n');
  await symlink(join(artifacts,'report.html'),join(artifacts,'alias.html'));
  const reports = portableArtifactArchive(artifacts,{retainHistoricalArtifacts:true});
  const reportChild = spawn(reports.command,reports.args,{stdio:['ignore','pipe','inherit']}), reportTar = join(root,'reports.tar');
  await Promise.all([pipeline(reportChild.stdout,createWriteStream(reportTar)),new Promise((r,j)=>{reportChild.on('error',j);reportChild.on('close',c=>c===0?r():j(Error('report export failed')));})]);
  await validateArchive(reportTar);
  const reportNames = (await exec('/usr/bin/tar',['-tf',reportTar])).stdout;
  for (const path of ['report.html','notes/venv/plan.md','debug/report.md','results.csv']) assert.ok(reportNames.includes('./'+path),path);
  for (const path of ['screenshot.png','recording.mp4','debug.json','trace.jsonl','trace.log','source.zip','alias.html','Desktop.app']) assert.ok(!reportNames.includes('./'+path),path);
  assert.equal(await readFile(join(artifacts,'screenshot.png'),'utf8'),'cold historical data');
  console.log('execution cold policy: retained originals, exact hot Git state, reports and local dependency placeholder passed');
} finally { await rm(root, { recursive: true, force: true }); }
